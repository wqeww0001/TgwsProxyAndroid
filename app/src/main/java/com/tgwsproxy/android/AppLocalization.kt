enum class AppLanguage(val code: String, val nativeName: String) {
    Ru("ru", "Русский"),
    En("en", "English"),
    Kk("kk", "Қазақша"),
    Uz("uz", "O‘zbekcha"),
    Es("es", "Español"),
    Fr("fr", "Français"),
    De("de", "Deutsch"),
    Pl("pl", "Polski"),
    Zh("zh", "中文"),
    Ja("ja", "日本語"),
    Ko("ko", "한국어"),
    Ka("ka", "ქართული"),
    Ar("ar", "العربية");

    val isCyrillicOrRu: Boolean
        get() = this == Ru || this == Kk

    companion object {
        fun from(code: String?): AppLanguage =
            entries.firstOrNull { it.code.equals(code, ignoreCase = true) } ?: Ru
    }
}

